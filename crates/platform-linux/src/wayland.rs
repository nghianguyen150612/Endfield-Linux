const DISCOVERY_TIMEOUT: Duration = Duration::from_secs(2);
const TOTAL_DISCOVERY_TIMEOUT: Duration = Duration::from_secs(5);

pub trait WaylandDisplayBackend: Send + Sync {
    fn inspect(&self, endpoint: &LocalWaylandEndpoint) -> Result<BackendObservation, BackendError>;
}

#[derive(Clone, Copy, Debug, Default)]
pub struct SystemWaylandBackend;

impl WaylandDisplayBackend for SystemWaylandBackend {
    fn inspect(&self, endpoint: &LocalWaylandEndpoint) -> Result<BackendObservation, BackendError> {
        let endpoint = endpoint.clone();
        let (sender, receiver) = mpsc::sync_channel(1);
        thread::Builder::new()
            .name("endfield-wayland-display-probe".to_owned())
            .spawn(move || {
                let result = UnixStream::connect(endpoint.socket_path())
                    .map_err(map_io_error)
                    .and_then(|stream| {
                        Connection::from_socket(stream).map_err(|_| BackendError {
                            kind: BackendErrorKind::Unavailable,
                        })
                    })
                    .and_then(|connection| inspect_connection(&connection));
                let _ = sender.send(result);
            })
            .map_err(|_| BackendError {
                kind: BackendErrorKind::Other,
            })?;
        receiver
            .recv_timeout(TOTAL_DISCOVERY_TIMEOUT)
            .map_err(|error| BackendError {
                kind: match error {
                    mpsc::RecvTimeoutError::Timeout => BackendErrorKind::TimedOut,
                    mpsc::RecvTimeoutError::Disconnected => BackendErrorKind::Unavailable,
                },
            })?
    }
}

#[derive(Default)]
struct WaylandState {
    outputs: Vec<OutputBuilder>,
    manager: Option<zxdg_output_manager_v1::ZxdgOutputManagerV1>,
    overflow: bool,
    topology_changed: bool,
    sync_done: bool,
    in_optional_pass: bool,
    output_protocol_version: Option<u32>,
}

#[derive(Default)]
struct OutputBuilder {
    global_id: u32,
    protocol_version: u32,
    proxy: Option<wl_output::WlOutput>,
    name: Option<String>,
    modes: Vec<LinuxDisplayMode>,
    scale: Option<ScaleFactor>,
    logical_x: Option<i32>,
    logical_y: Option<i32>,
    logical_width: Option<u32>,
    logical_height: Option<u32>,
    removed: bool,
    inconsistent: bool,
}

fn inspect_connection(connection: &Connection) -> Result<BackendObservation, BackendError> {
    let mut queue = connection.new_event_queue::<WaylandState>();
    let qh = queue.handle();
    let _registry = connection.display().get_registry(&qh, ());
    let mut state = WaylandState::default();
    bounded_roundtrip(connection, &mut queue, &qh, &mut state)?;

    let manager = state.manager.clone();
    state.in_optional_pass = true;
    let mut missing_proxy = false;
    if let Some(manager) = manager.as_ref() {
        for (index, output) in state.outputs.iter().enumerate() {
            if output.removed {
                continue;
            }
            let Some(proxy) = output.proxy.as_ref() else {
                missing_proxy = true;
                continue;
            };
            let index = index as u32;
            manager.get_xdg_output(proxy, &qh, index);
        }
    }
    state.topology_changed |= missing_proxy;
    // This second sync is required even when xdg-output is absent: the first
    // sync can complete before wl_output events generated by registry binds.
    bounded_roundtrip(connection, &mut queue, &qh, &mut state)?;
    state.in_optional_pass = false;

    let (outputs, mode_overflow) = finish_outputs(&state);
    let inconsistent = state.overflow
        || mode_overflow
        || state.topology_changed
        || state.outputs.iter().any(|output| output.inconsistent);
    Ok(BackendObservation {
        inventory_status: if inconsistent {
            OutputInventoryStatus::Inconsistent
        } else {
            OutputInventoryStatus::Enumerated
        },
        outputs,
        optional_logical_output_protocol: manager.is_some(),
        protocol_version: state.output_protocol_version.map(|version| (1, version)),
        screen_geometry: None,
        diagnostic: if state.overflow {
            Some("Wayland output count exceeded its limit")
        } else if inconsistent {
            Some("Wayland outputs changed or exceeded a discovery limit")
        } else {
            None
        },
    })
}

fn finish_outputs(state: &WaylandState) -> (Vec<BackendDisplayOutput>, bool) {
    let mut mode_overflow = false;
    let outputs = state
        .outputs
        .iter()
        .filter(|output| !output.removed)
        .take(MAX_DISPLAY_OUTPUTS)
        .map(|output| {
            let has_current = output.modes.iter().any(|mode| mode.current);
            let normalized_modes = normalize_modes(&output.modes);
            mode_overflow |= normalized_modes.overflow;
            let logical_geometry = output
                .logical_x
                .zip(output.logical_y)
                .zip(output.logical_width.zip(output.logical_height))
                .and_then(|((x, y), (width, height))| {
                    (width > 0 && height > 0).then_some(LogicalGeometry {
                        x,
                        y,
                        width,
                        height,
                    })
                });
            BackendDisplayOutput {
                name: output.name.clone(),
                state: if has_current {
                    DisplayOutputState::Active
                } else {
                    DisplayOutputState::Unknown
                },
                modes: normalized_modes.modes,
                primary: None,
                logical_geometry,
                scale: output.scale.or_else(|| {
                    (output.protocol_version >= 2).then_some(ScaleFactor {
                        numerator: 1,
                        denominator: 1,
                    })
                }),
                rotation_degrees: None,
            }
        })
        .collect();
    (outputs, mode_overflow)
}

struct NormalizedModes {
    modes: Vec<LinuxDisplayMode>,
    overflow: bool,
}

fn normalize_modes(modes: &[LinuxDisplayMode]) -> NormalizedModes {
    let mut normalized: Vec<LinuxDisplayMode> = Vec::new();
    let mut overflow = false;
    for mode in modes
        .iter()
        .filter(|mode| mode.is_valid())
        .take(MAX_DISPLAY_MODES * 2)
    {
        if let Some(existing) = normalized.iter_mut().find(|existing| {
            existing.width_pixels == mode.width_pixels
                && existing.height_pixels == mode.height_pixels
                && existing.refresh_rate == mode.refresh_rate
                && existing.interlaced == mode.interlaced
                && existing.doublescan == mode.doublescan
        }) {
            existing.current |= mode.current;
            existing.preferred |= mode.preferred;
        } else if normalized.len() < MAX_DISPLAY_MODES {
            normalized.push(mode.clone());
        } else {
            overflow = true;
        }
    }
    normalized.sort_by_key(|mode| {
        (
            !mode.current,
            !mode.preferred,
            mode.width_pixels,
            mode.height_pixels,
            mode.refresh_rate,
            mode.interlaced,
            mode.doublescan,
        )
    });
    NormalizedModes {
        modes: normalized,
        overflow,
    }
}

fn bounded_roundtrip(
    connection: &Connection,
    queue: &mut EventQueue<WaylandState>,
    qh: &QueueHandle<WaylandState>,
    state: &mut WaylandState,
) -> Result<(), BackendError> {
    state.sync_done = false;
    let _callback = connection.display().sync(qh, ());
    queue.flush().map_err(|_| BackendError {
        kind: BackendErrorKind::Unavailable,
    })?;
    let deadline = Instant::now() + DISCOVERY_TIMEOUT;
    while !state.sync_done {
        queue.dispatch_pending(state).map_err(|_| BackendError {
            kind: BackendErrorKind::Malformed,
        })?;
        if state.sync_done {
            break;
        }
        let Some(guard) = queue.prepare_read() else {
            continue;
        };
        let remaining = deadline.saturating_duration_since(Instant::now());
        if remaining.is_zero() {
            return Err(BackendError {
                kind: BackendErrorKind::TimedOut,
            });
        }
        let timeout = PollTimeout::try_from(remaining).unwrap_or(PollTimeout::MAX);
        let mut poll_fds = [PollFd::new(connection.as_fd(), PollFlags::POLLIN)];
        match poll(&mut poll_fds, timeout) {
            Ok(0) => {
                return Err(BackendError {
                    kind: BackendErrorKind::TimedOut,
                });
            }
            Ok(_) => {
                let _ = guard.read().map_err(|_| BackendError {
                    kind: BackendErrorKind::Unavailable,
                })?;
            }
            Err(Errno::EINTR) => continue,
            Err(_) => {
                return Err(BackendError {
                    kind: BackendErrorKind::Unavailable,
                });
            }
        }
    }
    queue.dispatch_pending(state).map_err(|_| BackendError {
        kind: BackendErrorKind::Malformed,
    })?;
    Ok(())
}

impl Dispatch<wl_registry::WlRegistry, ()> for WaylandState {
    fn event(
        state: &mut Self,
        registry: &wl_registry::WlRegistry,
        event: wl_registry::Event,
        _: &(),
        _: &Connection,
        qh: &QueueHandle<Self>,
    ) {
        match event {
            wl_registry::Event::Global {
                name,
                interface,
                version,
            } if interface == "wl_output" => {
                if state.outputs.len() >= MAX_DISPLAY_OUTPUTS {
                    state.overflow = true;
                    return;
                }
                if state.in_optional_pass {
                    state.topology_changed = true;
                }
                let protocol_version = version.clamp(1, 4);
                let proxy =
                    registry.bind::<wl_output::WlOutput, _, _>(name, protocol_version, qh, ());
                state.output_protocol_version = Some(
                    state
                        .output_protocol_version
                        .map_or(protocol_version, |current| current.max(protocol_version)),
                );
                state.outputs.push(OutputBuilder {
                    global_id: name,
                    protocol_version,
                    proxy: Some(proxy),
                    ..OutputBuilder::default()
                });
            }
            wl_registry::Event::Global {
                name,
                interface,
                version,
            } if interface == "zxdg_output_manager_v1" && state.manager.is_none() => {
                let version = version.clamp(1, 3);
                state.manager = Some(
                    registry.bind::<zxdg_output_manager_v1::ZxdgOutputManagerV1, _, _>(
                        name,
                        version,
                        qh,
                        (),
                    ),
                );
            }
            wl_registry::Event::GlobalRemove { name } => {
                if let Some(output) = state
                    .outputs
                    .iter_mut()
                    .find(|output| output.global_id == name)
                {
                    state.topology_changed = true;
                    output.removed = true;
                }
            }
            _ => (),
        }
    }
}

impl Dispatch<wl_output::WlOutput, ()> for WaylandState {
    fn event(
        state: &mut Self,
        _proxy: &wl_output::WlOutput,
        event: wl_output::Event,
        _: &(),
        _: &Connection,
        _: &QueueHandle<Self>,
    ) {
        let Some(output) = state.outputs.iter_mut().find(|output| {
            output
                .proxy
                .as_ref()
                .is_some_and(|candidate| candidate.id() == _proxy.id())
        }) else {
            return;
        };
        match event {
            wl_output::Event::Mode {
                flags,
                width,
                height,
                refresh,
            } => {
                if width <= 0 || height <= 0 || width > 32_768 || height > 32_768 {
                    output.inconsistent = true;
                    return;
                }
                let (current, preferred) = match flags {
                    WEnum::Value(flags) => (
                        flags.contains(wl_output::Mode::Current),
                        flags.contains(wl_output::Mode::Preferred),
                    ),
                    WEnum::Unknown(_) => (false, false),
                };
                if current {
                    for mode in &mut output.modes {
                        mode.current = false;
                    }
                }
                if output.modes.len() >= MAX_DISPLAY_MODES * 2 {
                    output.inconsistent = true;
                    return;
                }
                output.modes.push(LinuxDisplayMode {
                    width_pixels: width as u32,
                    height_pixels: height as u32,
                    refresh_rate: u32::try_from(refresh)
                        .ok()
                        .and_then(ExactRefreshRate::from_millihertz),
                    current,
                    preferred,
                    interlaced: None,
                    doublescan: None,
                });
            }
            wl_output::Event::Scale { factor } => {
                output.scale = u32::try_from(factor)
                    .ok()
                    .and_then(|factor| ScaleFactor::new(factor, 1));
                if output.scale.is_none() {
                    output.inconsistent = true;
                }
            }
            wl_output::Event::Name { name } => output.name = Some(name),
            _ => (),
        }
    }
}

impl Dispatch<zxdg_output_v1::ZxdgOutputV1, u32> for WaylandState {
    fn event(
        state: &mut Self,
        _: &zxdg_output_v1::ZxdgOutputV1,
        event: zxdg_output_v1::Event,
        index: &u32,
        _: &Connection,
        _: &QueueHandle<Self>,
    ) {
        let Some(output) = state.outputs.get_mut(*index as usize) else {
            state.topology_changed = true;
            return;
        };
        match event {
            zxdg_output_v1::Event::LogicalPosition { x, y } => {
                output.logical_x = Some(x);
                output.logical_y = Some(y);
            }
            zxdg_output_v1::Event::LogicalSize { width, height } => {
                if width > 0 && height > 0 {
                    output.logical_width = Some(width as u32);
                    output.logical_height = Some(height as u32);
                } else {
                    output.inconsistent = true;
                }
            }
            _ => (),
        }
    }
}

impl Dispatch<wl_callback::WlCallback, ()> for WaylandState {
    fn event(
        state: &mut Self,
        _: &wl_callback::WlCallback,
        event: wl_callback::Event,
        _: &(),
        _: &Connection,
        _: &QueueHandle<Self>,
    ) {
        if matches!(event, wl_callback::Event::Done { .. }) {
            state.sync_done = true;
        }
    }
}

delegate_noop!(WaylandState: ignore zxdg_output_manager_v1::ZxdgOutputManagerV1);

fn map_io_error(error: std::io::Error) -> BackendError {
    BackendError {
        kind: match error.kind() {
            std::io::ErrorKind::PermissionDenied => BackendErrorKind::PermissionDenied,
            std::io::ErrorKind::TimedOut | std::io::ErrorKind::WouldBlock => {
                BackendErrorKind::TimedOut
            }
            std::io::ErrorKind::NotFound | std::io::ErrorKind::ConnectionRefused => {
                BackendErrorKind::Unavailable
            }
            _ => BackendErrorKind::Other,
        },
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn exact_wayland_millihertz_is_preserved_without_rounding() {
        assert_eq!(
            ExactRefreshRate::from_millihertz(60_000),
            ExactRefreshRate::new(60, 1)
        );
        assert_eq!(
            ExactRefreshRate::from_millihertz(59_940),
            ExactRefreshRate::new(2_997, 50)
        );
        assert_eq!(
            ExactRefreshRate::from_millihertz(59_940).and_then(ExactRefreshRate::exact_whole_hertz),
            None
        );
    }

    #[test]
    fn mode_normalization_merges_duplicate_flags_and_orders_current_first() {
        let modes = [
            LinuxDisplayMode {
                width_pixels: 1920,
                height_pixels: 1080,
                refresh_rate: ExactRefreshRate::from_millihertz(60_000),
                current: false,
                preferred: true,
                interlaced: None,
                doublescan: None,
            },
            LinuxDisplayMode {
                width_pixels: 1920,
                height_pixels: 1080,
                refresh_rate: ExactRefreshRate::from_millihertz(60_000),
                current: true,
                preferred: false,
                interlaced: None,
                doublescan: None,
            },
        ];
        let normalized = normalize_modes(&modes);
        assert_eq!(normalized.modes.len(), 1);
        assert!(normalized.modes[0].current);
        assert!(normalized.modes[0].preferred);
        assert!(!normalized.overflow);
    }

    #[test]
    fn too_many_distinct_wayland_modes_are_reported_as_overflow() {
        let modes = (1..=MAX_DISPLAY_MODES + 1)
            .map(|width| LinuxDisplayMode {
                width_pixels: width as u32,
                height_pixels: 720,
                refresh_rate: None,
                current: false,
                preferred: false,
                interlaced: None,
                doublescan: None,
            })
            .collect::<Vec<_>>();
        let normalized = normalize_modes(&modes);
        assert_eq!(normalized.modes.len(), MAX_DISPLAY_MODES);
        assert!(normalized.overflow);
    }
}
